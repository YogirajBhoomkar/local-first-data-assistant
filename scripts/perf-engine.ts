import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { loadConfig } from "../packages/core/src/index.js";
import { DuckDbEngine } from "../packages/engine/src/index.js";
import { collectProbe, summarize } from "./probe-lib.js";

const folder = resolve(process.argv[2] ?? "./sample-big");
const config = loadConfig();
const engine = new DuckDbEngine({
  cacheDir: join(config.cacheDir, "perf"),
  ...config.engine,
  queryTimeoutMs: 120_000,
});

const queries: [string, string][] = [
  ["count", "SELECT COUNT(*) FROM t_policies"],
  ["filter", "SELECT COUNT(*) FROM t_policies WHERE region = 'EMEA' AND status = 'active'"],
  ["group-by", "SELECT line_of_business, region, SUM(premium_amount) FROM t_policies GROUP BY 1, 2"],
  ["top N", "SELECT broker_code, SUM(premium_amount) p FROM t_policies GROUP BY 1 ORDER BY p DESC, broker_code LIMIT 10"],
  ["join with claims", "SELECT p.line_of_business, SUM(c.paid_amount) FROM t_claims c JOIN t_policies p ON c.policy_id = p.policy_id GROUP BY 1"],
  ["date range", "SELECT COUNT(*), SUM(premium_amount) FROM t_policies WHERE CAST(inception_date AS DATE) BETWEEN DATE '2021-01-01' AND DATE '2021-12-31'"],
];

const t0 = Date.now();
const entries = await engine.scanFolder(folder);
const schemas = await engine.registerFiles(entries);
const registerMs = Date.now() - t0;
const sizeOf = (a: string) => ((entries.find((e) => e.alias === a)?.sizeBytes ?? 0) / 1024 ** 3).toFixed(2);

const rows: string[] = [];
let peakRss = 0;
const peak = () => (peakRss = Math.max(peakRss, process.memoryUsage().rss));
const mem = setInterval(peak, 200);
let slow = 0;
for (const [name, sql] of queries) {
  const s = Date.now();
  try {
    const r = await engine.runReadOnlySql(sql);
    const ms = Date.now() - s;
    if (ms > 60_000) slow++;
    rows.push(`| ${name} | ${ms} | ${r.rowCount} | ok |`);
  } catch (e) {
    rows.push(`| ${name} | ${Date.now() - s} | - | ${(e as Error).message.replace(/\|/g, "/")} |`);
    slow++;
  }
  peak();
}
clearInterval(mem);
await engine.close();

const probe = await collectProbe(config);
const md = `# Engine performance

Generated by \`scripts/perf-engine.ts\` on synthetic data.

## Machine
\`\`\`
${summarize(probe)}
\`\`\`

## Data
- policies.csv: ${sizeOf("policies")} GB, claims.csv: ${sizeOf("claims")} GB
- tables: ${schemas.map((s) => `${s.tableName} (~${s.rowCountEstimate} rows)`).join(", ")}
- engine settings: memory_limit ${config.engine.memoryLimit}, threads ${config.engine.threads}
- scan + register: ${registerMs} ms

## Queries (views over CSV, no conversion)
| query | ms | rows | result |
|---|---|---|---|
${rows.join("\n")}

Peak process RSS: ${(peakRss / 1024 ** 2).toFixed(0)} MB.
${slow ? `\n**${slow} quer${slow === 1 ? "y was" : "ies were"} slower than 60 s or failed.** Proposed fix: convert large CSVs once to Parquet in cacheDir.\n` : "\nAll queries finished under 60 s.\n"}`;
mkdirSync("eval/reports", { recursive: true });
writeFileSync("eval/reports/engine-perf.md", md);
console.log(md);
